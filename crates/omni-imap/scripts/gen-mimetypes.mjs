// Regenerates src/mime/mimetypes.rs from libmime's extension table, resolving
// each extension exactly as libmime.detectMimeType does (string value, else the
// entry whose subtype equals the extension, else the first entry).
// Usage (repository root): node crates/omni-imap/scripts/gen-mimetypes.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const libmimePath = require.resolve("libmime", {
  paths: [require.resolve("mailparser")],
});
const mimetypes = require(libmimePath.replace(/libmime\.js$/, "mimetypes.js"));

const rows = Object.keys(mimetypes.extensions)
  .sort()
  .map((extension) => {
    const value = mimetypes.extensions[extension];
    let resolved;
    if (typeof value === "string") resolved = value;
    else resolved = value.find((m) => m.split("/")[1] === extension) ?? value[0];
    return `    (${JSON.stringify(extension)}, ${JSON.stringify(resolved)}),`;
  });

const out = `//! Generated by \`scripts/gen-mimetypes.mjs\` from libmime's extension table.
//! Do not edit by hand. Sorted by extension for binary search.

pub(crate) const EXTENSIONS: &[(&str, &str)] = &[
${rows.join("\n")}
];
`;
writeFileSync(new URL("../src/mime/mimetypes.rs", import.meta.url), out);
