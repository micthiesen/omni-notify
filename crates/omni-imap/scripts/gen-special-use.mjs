// Regenerates src/protocol/special_use_names.rs from imapflow's special-use
// name tables (name -> flag, generic decoration tokens).
// Usage (repository root): node crates/omni-imap/scripts/gen-special-use.mjs
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const imapflowMain = require.resolve("imapflow");
const specialUse = require(imapflowMain.replace(/imap-flow\.js$/, "special-use.js"));

const index = new Map();
for (const flag of Object.keys(specialUse.names)) {
  for (const name of specialUse.names[flag]) if (!index.has(name)) index.set(name, flag);
}
const names = [...index.entries()].sort(([a], [b]) =>
  Buffer.compare(Buffer.from(a), Buffer.from(b)),
);

const source = readFileSync(imapflowMain.replace(/imap-flow\.js$/, "special-use.js"), "utf8");
const generic = source.match(/const GENERIC_TOKENS = new Set\(\s*\[([\s\S]*?)\]\.map/);
const tokens = [...generic[1].matchAll(/'([^']+)'/g)]
  .map((m) => m[1].toLowerCase().normalize("NFKC"))
  .sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));

// Rust string literal; invisible format characters are written as \u{..}.
const lit = (value) =>
  JSON.stringify(value).replace(/[\u00ad\u200b-\u200f\u2060\ufeff]/g, (c) =>
    `\\u{${c.codePointAt(0).toString(16)}}`,
  );

const out = `//! Generated by \`scripts/gen-special-use.mjs\` from imapflow's special-use
//! tables. Do not edit by hand. Both lists are sorted by UTF-8 bytes.

pub(crate) const NAMES: &[(&str, &str)] = &[
${names.map(([n, f]) => `    (${lit(n)}, ${lit(f)}),`).join("\n")}
];

pub(crate) const GENERIC_TOKENS: &[&str] = &[
${tokens.map((t) => `    ${lit(t)},`).join("\n")}
];
`;
writeFileSync(new URL("../src/protocol/special_use_names.rs", import.meta.url), out);
